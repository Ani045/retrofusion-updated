<h2 class="text-2xl sm:text-3xl font-bold text-stone-800 mt-12 mb-4 leading-snug font-display border-b-2 border-amber-500 pb-2 inline-block">Majestic Forts Trekking Through History And Romance</h2>

<p class="text-base sm:text-lg text-stone-700 leading-relaxed mb-5">Lonavala’s hill forts rise above deep valleys and the Pawna region, holding centuries of Maratha history. For couples, they offer shared adventure, quiet viewpoints and the thrill of reaching the top together.</p>

<p class="text-base sm:text-lg text-stone-700 leading-relaxed mb-5">Climbing stone steps, taking breathers on mossy landings and finally standing at the summit hand in hand can feel like a small victory with a huge view.</p>

