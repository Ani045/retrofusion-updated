<div>
<h3 class="text-xl sm:text-2xl font-semibold text-stone-800 mt-8 mb-3 leading-snug font-display"><strong>Can I swim in all the waterfalls in Lonavala?</strong> </h3>
<div>

<p class="text-base sm:text-lg text-stone-700 leading-relaxed mb-5">Swimming is often restricted or unsafe in many waterfall areas due to strong currents, hidden rocks, or sudden depth changes. Always adhere to warning signs and local guidelines. Bhushi Dam's stepped section allows for splashing, but direct swimming in the main reservoir is prohibited.</p>

</div>
</div>
<div>
<h3 class="text-xl sm:text-2xl font-semibold text-stone-800 mt-8 mb-3 leading-snug font-display"><strong>Are there any entry fees for Lonavala waterfall places?</strong> </h3>
<div>

<p class="text-base sm:text-lg text-stone-700 leading-relaxed mb-5">Most natural waterfalls do not have an entry fee. However, parking charges might apply at popular spots like Bhushi Dam. If visiting a waterfall within a private property or resort, there might be an entry fee.</p>

</div>
</div>
<div>
<h3 class="text-xl sm:text-2xl font-semibold text-stone-800 mt-8 mb-3 leading-snug font-display"><strong>What should I carry when visiting waterfalls in Lonavala?</strong> </h3>
<div>

<p class="text-base sm:text-lg text-stone-700 leading-relaxed mb-5">Carry extra clothes, a towel, waterproof bags for electronics, a first-aid kit, water, and some snacks. Wear comfortable, quick-drying clothes and sturdy, non-slip footwear.</p>

</div>
