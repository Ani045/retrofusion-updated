<p class="text-base sm:text-lg text-stone-700 leading-relaxed mb-5">Yes, while Lonavala is known for its vegetarian options, many restaurants like Parsi Dhaba and Kinara Village Dhaba offer a wide range of non-vegetarian dishes, including Punjabi and Mughlai cuisines.</p>

