<div>

<p class="text-base sm:text-lg text-stone-700 leading-relaxed mb-5">Early mornings are equally magical. The valleys are often filled with a surreal layer of fog, and the soft, golden light creates a completely different mood. For spots like Visapur or Duke's Nose, a sunrise shoot can be even more rewarding and crowd-free than a sunset one.</p>

